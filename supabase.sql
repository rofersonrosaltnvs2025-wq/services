-- Run this in Supabase SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  balance numeric(12,2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.services (
  id bigint primary key,
  provider_id text not null,
  name text not null,
  category text not null default 'Other',
  rate numeric(12,6) not null default 0,
  min_qty integer not null default 10,
  max_qty integer not null default 200000,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  provider_order_id text,
  service_id bigint references public.services(id),
  link text not null,
  quantity integer not null,
  charge numeric(12,2) not null,
  status text not null default 'Pending',
  created_at timestamptz not null default now()
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  type text not null,
  amount numeric(12,2) not null,
  reference text,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.services enable row level security;
alter table public.orders enable row level security;
alter table public.transactions enable row level security;

create policy "Users can read own profile" on public.profiles
for select using (auth.uid() = id);

create policy "Users can update own profile" on public.profiles
for update using (auth.uid() = id);

create policy "Everyone can read active services" on public.services
for select using (active = true);

create policy "Users can read own orders" on public.orders
for select using (auth.uid() = user_id);

create policy "Users can read own transactions" on public.transactions
for select using (auth.uid() = user_id);

-- Automatically create a profile after signup.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, username)
  values (new.id, coalesce(new.raw_user_meta_data->>'username', split_part(new.email,'@',1)));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();
